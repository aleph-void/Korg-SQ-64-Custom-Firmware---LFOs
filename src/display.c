void fb_pixel(int x, int y, uint8_t level)
{
    if ((unsigned)x >= DISP_WIDTH || (unsigned)y >= DISP_HEIGHT) return;
    uint8_t *byte = &framebuffer[(63 - y) * 128 + (x >> 1)];
    if (x & 1) *byte = (uint8_t)((*byte & 0x0f) | (level << 4));
    else *byte = (uint8_t)((*byte & 0xf0) | (level & 0x0f));
}

void fb_fill(int x, int y, int w, int h, uint8_t level)
{
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            fb_pixel(x + i, y + j, level);
}

void fb_clear(void)
{
    for (int i = 0; i < DISPLAY_BYTES; i++) framebuffer[i] = 0;
    dirty = true;
}

void fb_text(int x, int y, const char *s, uint8_t level)
{
    for (; *s; s++, x += 6) {
        unsigned c = (unsigned char)*s;
        if (c >= 'a' && c <= 'z') c -= 32;
        if (c < FONT_FIRST || c - FONT_FIRST >= sizeof(font) / 5) c = ' ';
        const uint8_t *g = font[c - FONT_FIRST];
        for (int col = 0; col < 5; col++)
            for (int row = 0; row < 7; row++)
                if ((g[col] >> row) & 1)
                    fb_pixel(x + col, y + row, level);
    }
}

void fb_number(int x, int y, int value, uint8_t level)
{
    char text[12];
    int at = sizeof(text) - 1;
    bool negative = value < 0;
    unsigned v = negative ? (unsigned)-value : (unsigned)value;
    text[at] = 0;
    do { text[--at] = (char)('0' + v % 10); v /= 10; } while (v && at);
    if (negative && at) text[--at] = '-';
    fb_text(x, y, &text[at], level);
}

void display_init(void)
{
    fb_clear();
    display_flush();
}

void display_flush(void)
{
    dirty = true;
}

uint8_t *display_framebuffer(void)
{
    return framebuffer;
}

void display_pump(void)
{
    /* Reading the stream control register also lets the board model finish
     * an in-flight transfer; EN clears when the frame has been consumed. */
    if (!dirty || (REG32(DISPLAY_DMA_STREAM) & DMA_CR_EN)) return;
    REG32(DISPLAY_DMA_STREAM + 8) = SPI_DISP_DR;
    REG32(DISPLAY_DMA_STREAM + 12) = (uint32_t)(uintptr_t)framebuffer;
    REG32(DISPLAY_DMA_STREAM + 4) = DISPLAY_BYTES / 2;
    REG32(DISPLAY_DMA_STREAM) = DMA_CR_EN | DMA_CR_DIR_M2P | DMA_CR_MINC | DMA_CR_MSIZE16;
    dirty = false;
}
